#!/usr/bin/env python3
"""
Golden-file snapshot tests for scripts/build.py.

WHY THIS FILE EXISTS
--------------------
build.py is ~3,900 lines and is the entire CMS: frontmatter parsing, the
family/stack-level models, see_also resolution, backlinks, the atlas grid,
the scatter geometry, the SVG dependency graph, eleven page generators, the
search index, the sitemap, RSS, llms.txt and the CLI dataset. Eight closed
bugs lived in it, and every one of them was found by a human reading the
rendered site. A snapshot of the rendered site is therefore the oracle that
matches how the defects actually present.

WHAT IT ASSERTS
---------------
  1. Golden snapshot. A small fixture corpus (tests/fixtures/content) is
     built into a temp directory and every generated byte is compared against
     tests/golden/. Any rendering change shows up as a reviewable diff.
  2. Determinism. The same corpus built twice must be byte-identical. This is
     the single most valuable assertion here: it is the property most likely
     to regress silently (a dict iteration order, a wall clock, a set) and it
     was hard-won in #91.
  3. Gates. A corpus with a bad family slug, an unresolvable see_also or an
     unknown stack_level must fail the build AND write zero files. A gate
     that runs after promotion is a post-mortem, not a gate.
  4. Escaping, page structure, JSON-LD validity, and CLI/web dataset parity.

ISOLATION
---------
Everything the build writes through is a module-level path constant in
observatory.config, so the sandbox below repoints all of them at a temp
directory:

    config.CONTENT_DIR      fixture corpus, not content/
    config.OUTPUT_DIR       temp dir, not the repo root
    config.SITE_ROOT        nonexistent temp path, so no committed OG card is
                            found and no git history is consulted
    config.FIRST_SEEN_PATH  temp file, not the committed scripts/first_seen.json
    export_cli_data.OUT_PATHS  temp file + the sandbox output, not the
                            committed cli/data/sensors.json
    gen_og.generate         stubbed to its documented browser-absent result,
                            because the real one drives headless Chromium and
                            DELETES committed og/cards/*.png for any sensor
                            not in the corpus it is handed

The runner additionally fingerprints the repo's own generated tree before and
after the suite and fails if a single byte moved. Tests that dirty the tree
they are meant to protect are worse than no tests.

USAGE
    .venv/bin/python scripts/test_build.py            # run the suite
    .venv/bin/python scripts/test_build.py --update   # re-bless the goldens
    make test

Re-bless goldens in the SAME commit as the rendering change that caused them
to move, and read the diff — it is the review artifact.
"""

